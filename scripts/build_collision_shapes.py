"""Bake signed alpha distance fields for fast, concavity-aware sprite contacts."""
from pathlib import Path
import base64
import json
import numpy as np
from PIL import Image
from scipy.ndimage import distance_transform_edt
root=Path(__file__).resolve().parents[1]
files=list((root/'assets_webp/celulas').glob('*.webp'))+list((root/'assets_webp/new_size').glob('*.webp'))
shapes={}
for p in sorted(files):
    im=Image.open(p).convert('RGBA')
    ratio=128/max(im.size)
    w,h=max(2,round(im.width*ratio)),max(2,round(im.height*ratio))
    alpha=im.getchannel('A').resize((w,h),Image.Resampling.BOX)
    mask=np.array(alpha)>=48
    sdf=distance_transform_edt(~mask)-distance_transform_edt(mask)
    values=np.clip(np.rint(sdf*2),-127,127).astype(np.int8)
    bounds=im.getchannel('A').point(lambda a:255 if a>=48 else 0).getbbox()
    ys,xs=np.nonzero(np.array(im.getchannel('A'))>=48)
    radius=float(np.max(np.hypot(xs-im.width/2,ys-im.height/2)))
    by,bx=np.nonzero(mask & (distance_transform_edt(mask)<=1.5))
    indices=set(np.linspace(0,len(bx)-1,min(32,len(bx)),dtype=int).tolist())
    for angle in np.linspace(0,2*np.pi,8,endpoint=False):
        indices.add(int(np.argmax(bx*np.cos(angle)+by*np.sin(angle))))
    points=[[(float(bx[i])+.5)*im.width/w-im.width/2,(float(by[i])+.5)*im.height/h-im.height/2] for i in sorted(indices)]
    shapes[p.stem]={'points':points,'radius':radius,'width':im.width,'height':im.height,'w':w,'h':h,'bounds':bounds,'data':base64.b64encode(values.tobytes()).decode()}
(root/'world-shapes.js').write_text('// Generated by scripts/build_collision_shapes.py; signed half-grid distances.\nconst SPRITE_SHAPE_DATA = '+json.dumps(shapes,separators=(',',':'))+';\n')
print(f'{len(shapes)} signed distance fields baked')
